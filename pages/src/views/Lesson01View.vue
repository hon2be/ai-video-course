  <section class="lesson-section" id="sec2-1">
    <h2>2.1 씬과 컷의 개념</h2>
    <p><strong>씬(Scene)</strong>: 같은 장소·시간·상황에서 진행되는 이야기 단위.</p>
    <p><strong>컷(Cut)</strong>: 씬 안에서 카메라 위치나 앵글이 바뀌는 최소 단위.</p>
    <div class="data-table-wrap">
      <table class="data-table">
